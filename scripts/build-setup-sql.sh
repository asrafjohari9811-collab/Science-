#!/usr/bin/env bash
# Combines all migrations and the content seed into supabase/setup_all.sql (paste into Supabase SQL Editor).
set -euo pipefail
cd "$(dirname "$0")/.."
{
  echo "-- Science Quest Year 2: complete database setup. GENERATED by scripts/build-setup-sql.sh"
  echo "-- Run once in Supabase → SQL Editor on a new project."
  for f in supabase/migrations/*.sql supabase/seed/content.sql; do echo; echo "-- ===== $f ====="; cat "$f"; done
} > supabase/setup_all.sql
echo "Wrote supabase/setup_all.sql"
